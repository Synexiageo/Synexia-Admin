import { ask, say, OWNER } from "../lib/bot.mjs";

export const config = { schedule: "0 5 * * *" };   // 05:00 UTC = 09:00 თბილისი

export default async () => {
  if (!OWNER) return new Response("ok");

  const prompt = `დილის შეჯამება. ბაზიდან აიღე და მოკლედ დაწერე:
1. გუშინ რამდენი ლიდი შემოვიდა (ზოგადი სეგმენტი) და რამდენი იყო ⭐ ცხელი
2. გუშინ რამდენი ლიდი დამუშავდა — ანუ სტატუსი შეეცვალა — და რამდენი გახდა Onboarded
3. ახლა რამდენი დაურეკავი New Lead არის და ვის რამდენი აქვს
4. გუშინ რამდენი ანკეტა შეივსო
5. თუ რამე თვალში საცემია — მაგალითად ერთ აგენტთან სხვებზე ბევრად მეტი დაგროვდა,
   ან ლიდების ნაკადი მკვეთრად დაეცა — ბოლოს ერთი წინადადებით თქვი.

დიასახლისების სეგმენტი არ ჩათვალო. დასაწყისში მისალმება არ დაწერო.`;

  try {
    const { text } = await ask(OWNER, [{ role: "user", content: prompt }]);
    await say(OWNER, "☀️ დილის შეჯამება\n\n" + text);
  } catch (e) {
    await say(OWNER, "დილის შეჯამება ვერ გავაკეთე: " + String(e.message).slice(0, 300));
  }
  return new Response("ok");
};
